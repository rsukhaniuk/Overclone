    internal static bool IsAddedResource(string name) => AddedResources.Contains(name);

    public static bool MatchesComponents(IReadOnlyDictionary<string, NativeResourcePin> pins)
    {
        if (!Ready || pins.Count != ResourceCount || pins.Values.Sum(pin => (long)pin.Length) != TotalBytes
            || NativeRuntimePackage.ResourceIdentity(pins.Values).Hex != ClosureHash) return false;
        var baseline = pins.Where(pair => !IsAddedResource(pair.Key))
            .ToDictionary(pair => pair.Key, pair => pair.Value, StringComparer.Ordinal);
        return NativeCompilerInputBudgetPins.MatchesComponents(baseline);
    }
