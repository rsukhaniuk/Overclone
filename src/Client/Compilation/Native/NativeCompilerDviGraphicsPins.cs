    internal static bool IsDviSharedFont(string name) => DviSharedFonts.Contains(name);
    internal static bool IsDviOnlyResource(string name) => name is ColorConfiguration or "times.sty";
    internal static bool NoticeName(string? name) => name == Notice;

    public static bool MatchesComponents(IReadOnlyDictionary<string, NativeResourcePin> pins)
    {
        if (pins.Count != ResourceCount || pins.Values.Sum(pin => (long)pin.Length) != TotalBytes
            || NativeRuntimePackage.ResourceIdentity(pins.Values).Hex != ClosureHash) return false;
        var parent = pins.Where(p => !IsDviOnlyResource(p.Key) && !NoticeName(p.Key))
            .ToDictionary(p => p.Key, p => p.Value, StringComparer.Ordinal);
        const string converter = "dvi-map-converter.wasm";
        parent[converter] = new(converter, NativeCompilerInputBudgetPins.DviConverterWasmLength,
            NativeCompilerInputBudgetPins.DviConverterWasmHash);
        return NativeCompilerCourseworkPins.MatchesComponents(parent);
    }
